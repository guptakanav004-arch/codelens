"use client";

import { useEffect, useRef, useState } from "react";
import { RefreshCw } from "lucide-react";
import type { ExplanationLevel, LanguageId, ReviewResponse } from "@/types/review";
import { api, ApiClientError } from "@/services/api";
import { Markdown } from "@/components/ui/Markdown";
import { Skeleton } from "@/components/ui/Skeleton";
import { Button } from "@/components/ui/Button";
import { Tabs } from "@/components/ui/Tabs";
import { CopyButton } from "@/components/ui/CopyButton";
import { useToast } from "@/components/ui/Toast";

const LEVELS: { id: ExplanationLevel; label: string; hint: string }[] = [
  { id: "beginner", label: "Beginner", hint: "Simple language, no jargon" },
  { id: "intermediate", label: "Intermediate", hint: "Logic, data flow and technical details" },
  { id: "advanced", label: "Advanced", hint: "Architecture, decisions, performance and trade-offs" },
];

export function ExplanationTab({
  review,
  code,
  language,
}: {
  review: ReviewResponse;
  code: string;
  language: LanguageId;
}) {
  const [level, setLevel] = useState<ExplanationLevel>(review.explanation_level);
  const cache = useRef<Partial<Record<ExplanationLevel, string>>>({
    [review.explanation_level]: review.explanation,
  });
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [, force] = useState(0);
  const { toast } = useToast();

  async function load(target: ExplanationLevel) {
    setLoading(true);
    setError(null);
    try {
      const res = await api.explain({ code, language, level: target });
      cache.current[target] = res.explanation;
    } catch (e) {
      const msg = e instanceof ApiClientError ? e.message : "Failed to generate explanation.";
      setError(msg);
      toast(msg, "error");
    } finally {
      setLoading(false);
      force((n) => n + 1);
    }
  }

  useEffect(() => {
    if (!cache.current[level] && !loading && !error) void load(level);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [level]);

  const text = cache.current[level];
  const hint = LEVELS.find((l) => l.id === level)?.hint;

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between gap-2">
        <Tabs
          items={LEVELS.map((l) => ({ id: l.id, label: l.label }))}
          value={level}
          onChange={(l) => {
            setError(null);
            setLevel(l);
          }}
          variant="pill"
          label="Explanation level"
        />
        {text && <CopyButton text={text} label="Copy" />}
      </div>
      <p className="text-xs text-subtle">{hint} · generated by Nemotron from your submitted code.</p>

      {loading && (
        <div className="space-y-2.5 rounded-xl border border-line bg-panel2/40 p-4">
          <Skeleton className="h-4 w-1/3" />
          <Skeleton className="h-3 w-full" />
          <Skeleton className="h-3 w-11/12" />
          <Skeleton className="h-3 w-4/5" />
          <Skeleton className="mt-3 h-4 w-1/4" />
          <Skeleton className="h-3 w-full" />
          <Skeleton className="h-3 w-3/5" />
        </div>
      )}
      {!loading && error && (
        <div className="rounded-xl border border-danger/30 bg-danger/5 p-4 text-sm">
          <p className="text-danger">{error}</p>
          <Button className="mt-3" size="sm" onClick={() => load(level)}>
            <RefreshCw className="h-3.5 w-3.5" /> Retry
          </Button>
        </div>
      )}
      {!loading && !error && text && (
        <div className="animate-fade-up rounded-xl border border-line bg-panel2/40 p-4">
          <Markdown text={text} />
        </div>
      )}
      {!loading && !error && !text && <p className="text-sm text-muted">No explanation available.</p>}
    </div>
  );
}
